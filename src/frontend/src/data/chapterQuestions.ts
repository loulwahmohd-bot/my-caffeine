export type Difficulty = "easy" | "medium" | "hard";

export interface LocalChoice {
  id: number;
  text: string;
  correct: boolean;
}

export interface LocalQuestion {
  id: number;
  text: string;
  difficulty: Difficulty;
  choices: LocalChoice[];
}

export interface ChapterData {
  id: number;
  title: string;
  questions: LocalQuestion[];
}

function q(
  id: number,
  text: string,
  difficulty: Difficulty,
  a: string,
  b: string,
  c: string,
  d: string,
  correct: "a" | "b" | "c" | "d",
): LocalQuestion {
  return {
    id,
    text,
    difficulty,
    choices: [
      { id: 1, text: a, correct: correct === "a" },
      { id: 2, text: b, correct: correct === "b" },
      { id: 3, text: c, correct: correct === "c" },
      { id: 4, text: d, correct: correct === "d" },
    ],
  };
}

